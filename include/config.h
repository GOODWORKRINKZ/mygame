#pragma once

// ============================================================
//  Распиновка (ESP32-C3). Все пины — обычные GPIO, меняйте свободно.
//  НЕ используйте GPIO2, GPIO8, GPIO9 (страппинг/загрузка) и
//  GPIO18/19 (USB), GPIO20/21 (UART0) на большинстве плат.
// ============================================================
// GPIO10 на некоторых платах ESP32-C3 (DevKitC-02 и подобных) — это
// встроенный RGB-LED. Используем GPIO2, он точно свободен.
#define PIN_LED         2   // DATA ленты WS2812 (через резистор 330-470 Ом)
// #define PIN_LED_ALT 8 // раскомментируй для теста на другом пине
#define PIN_OLED_SDA    4   // OLED I2C SDA
#define PIN_OLED_SCL    5   // OLED I2C SCL
#define PIN_BTN_P1      0   // зелёная кнопка (игрок 1)
#define PIN_BTN_P2      1   // синяя кнопка (игрок 2)
#define PIN_BTN_MENU    3   // маленькая кнопка управления
#define PIN_BUZZER      7   // бузер (через транзистор)
#define PIN_VIBRO       6   // вибромоторчик (через транзистор)

// ============================================================
//  Светодиодная лента
// ============================================================
#define LED_COUNT       32
#define LED_BRIGHTNESS  80        // 0..255, чтобы не слепить
#define MIDDLE_LO       8         // средняя зона: 16 светодиодов [8..23]
#define MIDDLE_HI       23

// ============================================================
//  OLED 128x64 I2C
// ============================================================
#define OLED_ADDR       0x3C      // чаще 0x3C, иногда 0x3D (код пробует оба)
#define OLED_WIDTH      128
#define OLED_HEIGHT     64

// ============================================================
//  Кнопки
// ============================================================
// Кнопка замыкает GPIO на GND, подтяжка — внутренняя INPUT_PULLUP.
#define BTN_DEBOUNCE_MS 8         // антидребезг
#define BTN_LONG_MS     800       // удержание = "долгое нажатие"

// ============================================================
//  Параметры игр
// ============================================================
#define ROUNDS_TO_WIN      3      // до скольки побед в матче
#define SHOOTER_HP         5      // ХП базы в стрелялке
#define SHOT_SPEED_MS      90     // скорость снаряда (мс на 1 светодиод)
#define SHOT_COOLDOWN_MS   250    // перезарядка выстрела
#define PONG_TICK_MS       70     // такт игры пинг-понг
#define PONG_PADDLE_MAX    8      // макс. "энергия" шпингалета (8 пикселей)
